@login_required(login_url='adminlogin')
@user_passes_test(is_admin)
def discharge_patient_view(request, pk):
    patient = models.Patient.objects.get(id=pk)
    days = date.today() - patient.admitDate

    assignedDoctor = models.User.objects.filter(
        id=patient.assignedDoctorId
    ).first()

    if assignedDoctor is None:
        return HttpResponse(
            "This patient has no assigned doctor. Assign an approved doctor first.",
            status=400
        )

    d = days.days
    patientDict = {
        'patientId': pk,
        'name': patient.get_name,
        'mobile': patient.mobile,
        'address': patient.address,
        'symptoms': patient.symptoms,
        'admitDate': patient.admitDate,
        'todayDate': date.today(),
        'day': d,
        'assignedDoctorName': assignedDoctor.first_name,
    }

    if request.method == 'POST':
        room_charge = int(request.POST['roomCharge']) * d
        doctor_fee = int(request.POST['doctorFee'])
        medicine_cost = int(request.POST['medicineCost'])
        other_charge = int(request.POST['OtherCharge'])

        patientDict.update({
            'roomCharge': room_charge,
            'doctorFee': doctor_fee,
            'medicineCost': medicine_cost,
            'OtherCharge': other_charge,
            'total': room_charge + doctor_fee + medicine_cost + other_charge,
        })

        pDD = models.PatientDischargeDetails()
        pDD.patientId = pk
        pDD.patientName = patient.get_name
        pDD.assignedDoctorName = assignedDoctor.first_name
        pDD.address = patient.address
        pDD.mobile = patient.mobile
        pDD.symptoms = patient.symptoms
        pDD.admitDate = patient.admitDate
        pDD.releaseDate = date.today()
        pDD.daySpent = d
        pDD.medicineCost = medicine_cost
        pDD.roomCharge = room_charge
        pDD.doctorFee = doctor_fee
        pDD.OtherCharge = other_charge
        pDD.total = room_charge + doctor_fee + medicine_cost + other_charge
        pDD.save()

        return render(
            request,
            'hospital/patient_final_bill.html',
            context=patientDict
        )

    return render(
        request,
        'hospital/patient_generate_bill.html',
        context=patientDict
    )


